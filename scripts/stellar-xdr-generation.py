#!/usr/bin/env python3
"""Regenerate the SDK's Swift XDR files in an empty directory and compare Git blobs."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile

SDK = 'b5dac0a6e8ff312d597c9a3b4269b03131d66e0d'
SPEC = 'c40231c76bf2ebce76b24aa11c72508ac3eaa329'
GENERATOR = '99390b91b0f15c1f0ef7a55b6cf12d0700531336'
OUTPUT = 'stellarsdk/stellarsdk/responses/xdr'
MARKER = b'automatically generated by xdrgen'
DENY_NETWORK = '(version 1) (allow default) (deny network*)'

def git(repo, *args):
    return subprocess.check_output(['git', '-C', repo, *args])

def digest(data):
    return hashlib.sha256(data).hexdigest()

def generate(sdk, spec, bundle, output, app):
    lock = app/'OathAtmosphere.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved'
    pins = json.loads(lock.read_text())
    assert any(p['state']['revision'] == SDK and p['repositoryURL'] == 'https://github.com/Soneso/stellar-ios-mac-sdk.git'
               for p in pins['object']['pins'])
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        archive = root/'inputs.tar'
        with archive.open('wb') as stream:
            subprocess.run(['git','-C',sdk,'archive',SDK,'tools/xdr-generator','xdr'],stdout=stream,check=True)
        with tarfile.open(archive) as data:
            data.extractall(root,filter='data')
        inputs = {}
        for schema in sorted((root/'xdr').glob('*.x')):
            official = git(spec,'show',SPEC+':'+schema.name)
            if schema.read_bytes() != official: raise ValueError('Schema differs from official source: '+schema.name)
            inputs[schema.name] = digest(official)
        if not inputs: raise ValueError('No schema files')
        generator = root/'tools/xdr-generator'
        lockfile = (generator/'Gemfile.lock').read_bytes()
        if GENERATOR.encode() not in lockfile: raise ValueError('Unexpected generator pin')
        dest = root/OUTPUT
        dest.mkdir(parents=True)
        env = dict(os.environ,BUNDLE_FROZEN='true')
        env['BUNDLE_APP_CONFIG'] = str(root/'bundle-config')
        subprocess.run(['sandbox-exec','-p',DENY_NETWORK,str(bundle),'_2.7.2_','exec','ruby','generate.rb'],
                       cwd=generator,env=env,check=True,stdout=subprocess.DEVNULL)
        emitted = {p.relative_to(root).as_posix(): p.read_bytes() for p in dest.rglob('*.swift')}
        entries = git(sdk,'ls-tree','-rz',SDK,'--',OUTPUT).split(b'\0')
        expected = {}
        for entry in filter(None,entries):
            metadata,path=entry.split(b'\t',1)
            if not path.endswith(b'.swift'): continue
            blob = git(sdk,'cat-file','blob',metadata.split()[2].decode())
            if MARKER in blob: expected[path.decode()] = blob
        if not expected or set(expected) != set(emitted):
            raise ValueError('Generated and checked-in file sets differ: '+str(sorted(set(expected)^set(emitted))))
        mismatches = {p:{'committed':digest(expected[p]),'generated':digest(emitted[p])} for p in expected if emitted[p]!=expected[p]}
        result={'check':'stellar-xdr-generation','source_commit':git(app,'rev-parse','HEAD').decode().strip(),
                'sdk_commit':SDK,'schema_commit':SPEC,'generator_commit':GENERATOR,'bundler_version':'2.7.2',
                'ruby_version':subprocess.check_output(['ruby','--version'],text=True).strip(),
                'gemfile_lock_sha256':digest(lockfile),'schema_sha256':inputs,'generated_count':len(emitted),
                'matching_files':{p:digest(v) for p,v in sorted(expected.items()) if p not in mismatches},'mismatches':mismatches,
                'scope':'Byte equality to regenerated Swift source. No semantic assurance for the generator or a runtime transaction.'}
        output.parent.mkdir(parents=True,exist_ok=True)
        output.write_text(json.dumps(result,indent=2)+'\n')
        if mismatches: raise ValueError('Recorded differing files: '+str(len(mismatches)))

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ['sdk','spec','bundle','output','app']:parser.add_argument('--'+name,type=Path,required=True)
    args=parser.parse_args()
    generate(**{k:v.resolve() for k,v in vars(args).items()})
